def parse_sidebar(doc_root: str) -> list[Item]:
    """Every module item, from the `sidebar-items.js` file of every module directory."""
    items: list[Item] = []
    for directory, _dirs, files in os.walk(doc_root):
        if "sidebar-items.js" not in files:
            continue
        if os.path.basename(directory) == "src" or f"{os.sep}src{os.sep}" in directory + os.sep:
            continue
        module = module_of(doc_root, directory)
        sidebar = read_text(os.path.join(directory, "sidebar-items.js"))
        match = re.search(r"window\.SIDEBAR_ITEMS = (\{.*\});", sidebar, re.S)
        if match is None:
            raise SystemExit(f"cannot read the sidebar of module `{module}`: unexpected format")
        entries = json.loads(match.group(1))
        for kind, names in sorted(entries.items()):
            if kind not in MODULE_ITEM_KINDS:
                # `primitive`, `keyword`, ... are rustdoc's cross-reference entries, not items.
                if kind in {"type", "constant"}:
                    raise SystemExit(f"unexpected sidebar kind `{kind}` in module `{module}`")
                continue
            for name in names:
                path = f"{module}::{name}" if module else name
                items.append(Item(path=path, kind=MODULE_ITEM_KINDS[kind]))
    return items


def item_page(doc_root: str, item: Item) -> str | None:
    """The HTML page of a module item, if rustdoc generated one."""
    module, _, name = item.path.rpartition("::")
    directory = os.path.join(doc_root, *module.split("::")) if module else doc_root
    prefix = {"struct": "struct", "enum": "enum", "trait": "trait", "fn": "fn"}.get(item.kind, item.kind)
    page = os.path.join(directory, f"{prefix}.{name}.html")
    return page if os.path.isfile(page) else None


IMPL_HEADER = re.compile(
    r'<section id="impl-[^"]*"[^>]*>(?:\s*<a class="src[^>]*>.*?</a>)?'
    r'(?:\s*<a href="[^"]*" class="anchor">.*?</a>)?\s*<h3 class="code-header">(.*?)</h3>',
    re.S,
)
MEMBER_HEADER = re.compile(
    r'<section id="(method|tymethod|associatedconstant|associatedtype|structfield|variant)\.'
    r'([A-Za-z_0-9]+)"[^>]*>',
)
CODE_HEADER = re.compile(r'<h[34] class="code-header">(.*?)</h[34]>', re.S)


def enclosing_type_name(impl_header: str) -> str:
    """The type an impl header is `for` (`impl SBase for Model` -> `Model`), or the impl subject."""
    text = re.sub(r"\s+", " ", impl_header)
    if " for " in text:
        return text.rsplit(" for ", 1)[1].strip()
    return text[len("impl") :].strip()


def parse_members(doc_root: str, item: Item) -> list[Item]:
    """Every member rustdoc lists on an item page, grouped by the impl block it belongs to."""
    page = item_page(doc_root, item)
    if page is None:
        return []
    html = read_text(page)
    description = re.search(r'<meta name="description" content="(.*?)">', html, re.S)
    if description is not None:
        item.doc = strip_html(description.group(1))
    # A re-export of another crate's item has no members of its own to classify.
    members: list[Item] = []
    impl_positions = [(m.start(), m) for m in IMPL_HEADER.finditer(html)]
    if not impl_positions:
        return []
    # Variants and fields are not inside an impl block: rustdoc lists them on the item's own page,
    # above the impls, so they are collected separately.
    seen = set()
    for member in MEMBER_HEADER.finditer(html):
        if member.group(1) not in {"variant", "structfield"}:
            continue
        name = member.group(2)
        if name in seen:
            continue
        seen.add(name)
        segment = html[member.end() : member.end() + 1200]
        header_match = CODE_HEADER.search(segment)
        members.append(
            Item(
                path=f"{item.path}::{name}",
                kind=MEMBER_SECTIONS[member.group(1)],
                signature=strip_html(header_match.group(1)) if header_match else "",
                owner=item.path.rpartition("::")[2],
            )
        )
    for index, (start, match) in enumerate(impl_positions):
        end = impl_positions[index + 1][0] if index + 1 < len(impl_positions) else len(html)
        header = strip_html(match.group(1))
        owner = enclosing_type_name(header)
        trait = header[len("impl") :].strip()
        trait = trait.split(" for ")[0].strip() if " for " in trait else ""
        # `impl<T> Foo for Twhere T: Bar` -- rustdoc renders the `where` clause inline.
        trait = re.sub(r"^<.*?>", "", trait).strip()
        if trait.startswith("!") or trait in {"Deref", "DerefMut"}:
            continue
        body = html[start:end]
        for member in MEMBER_HEADER.finditer(body):
            kind, name = member.group(1), member.group(2)
            segment = body[member.end() : member.end() + 1500]
            header_match = CODE_HEADER.search(segment)
            signature = strip_html(header_match.group(1)) if header_match else ""
            members.append(
                Item(
                    path=f"{item.path}::{name}",
                    kind=MEMBER_SECTIONS[kind],
                    signature=signature,
                    impl_trait=normalize_trait(trait),
                    owner=owner,
                )
            )
    return members


def normalize_trait(trait: str) -> str:
    """`impl<T> ExtensionCast for T where T: ..` -> `ExtensionCast`; `impl Model` -> ``."""
    if not trait:
        return ""
    trait = trait.replace("where", " where ")
    name = trait.split(" where ")[0].strip()
    name = re.sub(r"^<[^>]*>\s*", "", name)
    # `From<Model> for XmlElement` and friends: keep the trait name only.
    name = name.split("<")[0].strip()
    return name


def collect(doc_root: str, src_root: str) -> list[Item]:
    module_items = parse_sidebar(doc_root)
    seen: set[tuple[str, str]] = set()
    unique: list[Item] = []
    for item in module_items:
        key = (item.path, item.kind)
        if key in seen:
            continue
        seen.add(key)
        unique.append(item)
    members: list[Item] = []
    for item in unique:
        members.extend(parse_members(doc_root, item))
    # `Document` is a re-export from `biodivine-lib-xml-dom`: it has no members here, and rustdoc
    # links to the other crate instead of generating a page. Mark it so the classifier can act.
    mark_foreign_reexports(src_root, unique)
    mark_wrapper_types(src_root, unique)
    return unique + members


def mark_foreign_reexports(src_root: str, items: list[Item]) -> None:
    """Mark the items that are re-exports of another crate (`pub use biodivine_lib_xml_dom::..`).

    The crate re-exports `biodivine-lib-xml-dom`'s `Document` so that an SBML user needs one import
    for the document type; the type is not this crate's, and its Python class is xml-dom's. The
    sources are the reliable place to see that: rustdoc renders a re-export and a local declaration
    the same way.
    """
    imported: dict[str, str] = {}
    pattern = re.compile(r"pub use (biodivine_lib_[a-z_]+)::(\{[^}]*\}|[A-Za-z_0-9]+)", re.S)
    for directory, _dirs, files in os.walk(src_root):
        for name in files:
            if not name.endswith(".rs"):
                continue
            for match in pattern.finditer(read_text(os.path.join(directory, name))):
                crate_name = match.group(1)
                body = match.group(2).strip("{}")
                for entry in body.split(","):
                    entry = entry.strip()
                    if not entry:
                        continue
                    local = entry.split(" as ")[-1].strip()
                    imported[local] = crate_name
    if not imported:
        raise SystemExit(
            "no `pub use biodivine_lib_*::` re-export found in the sources: the parser's"
            " assumption about how this crate re-exports the XML layer no longer holds"
        )
    for item in items:
        name = item.path.rpartition("::")[2]
        if item.kind in {"struct", "enum", "trait", "type"} and name in imported:
            item.impl_trait = f"@{imported[name]}"


def mark_wrapper_types(src_root: str, items: list[Item]) -> None:
    """Record which structs are declared with `#[sbml_object(..)]` (the thin SBML wrappers).

    The declaration may span several lines and may be followed by further attributes (a
    documentation figure, another derive), so the scan looks for the declaration and then for the
    next `pub struct` after it, instead of assuming the two are adjacent.
    """
    names: set[str] = set()
    declaration = re.compile(r"#\[sbml_object\(")
    struct_after = re.compile(r"pub struct ([A-Za-z_0-9]+)")
    for directory, _dirs, files in os.walk(src_root):
        for name in files:
            if not name.endswith(".rs"):
                continue
            text = read_text(os.path.join(directory, name))
            for match in declaration.finditer(text):
                found = struct_after.search(text, match.end())
                if found is not None and found.start() - match.end() < 1200:
                    names.add(found.group(1))
    for item in items:
        if item.kind == "struct" and item.path.rpartition("::")[2] in names:
            item.impl_trait = "@wrapper"


# ---------------------------------------------------------------------------------------------
# Classification: bound / not bound, with the Python name and a reason
# ---------------------------------------------------------------------------------------------


@dataclass
class Rule:
    """One classification rule: the first rule that matches an item classifies it."""

    ident: str
    description: str
    status: str
    python: str
    reason: str
    matches: callable
    #: Filled in by `classify`; used for the rule table and for the self-check.
    matched: list[str] = field(default_factory=list)


def is_accessor(item: Item) -> bool:
    """Whether the item is an inherent method of a wrapper type (not a trait-provided one)."""
    return (
        item.kind == "method"
        and not item.impl_trait
        and item.signature.startswith(("pub fn", "fn "))
    )


def returns(item: Item, *names: str) -> bool:
    signature = item.signature
    for name in names:
        if re.search(rf"->\s*{name}\b", signature) or re.search(rf"->\s*Option<{name}", signature):
            return True
    return False


SUBTYPE_SUPERS: dict[str, str] = {}


def read_inheritance(src_root: str) -> dict[str, str]:
    """The `Sub -> Super` map of the crate, from its own inheritance declarations.

    Rustdoc lists the blanket `XmlSubtype` implementation on *every* wrapper type page, so the
    documentation alone cannot tell a subtype from a supertype: the source can, and it is the same
    fact the Rust compiler checks.
    """
    found: dict[str, str] = {}
    pattern = re.compile(
        r"impl(?:<[^>]*>)?\s*Xml(?:Named)?Subtype<([A-Za-z_0-9:]+)>\s*for\s+([A-Za-z_0-9]+)"
    )
    for directory, _dirs, files in os.walk(src_root):
        for name in files:
            if not name.endswith(".rs"):
                continue
            for match in pattern.finditer(read_text(os.path.join(directory, name))):
                found[match.group(2)] = match.group(1)
    return found


def owner_is(item: Item, *names: str) -> bool:
    """Whether the item is a member of one of the named types."""
    return item.path.rpartition("::")[0].rpartition("::")[2] in names


def member_is(kind: str, impl_trait: str = "", prefix: str = "") -> callable:
    def matches(item: Item) -> bool:
        return (
            item.kind == kind
            and item.impl_trait == impl_trait
            and item.path.rpartition("::")[2].startswith(prefix)
        )

    return matches


PROPERTY_MARKERS = (
    "OptionalSbmlProperty",
    "RequiredSbmlProperty",
    "OptionalProperty",
    "RequiredProperty",
    "OptionalDynamicProperty",
    "RequiredDynamicProperty",
    "OptionalXmlProperty",
    "RequiredXmlProperty",
)
CHILD_MARKERS = (
    "OptionalSbmlChild",
    "RequiredSbmlChild",
    "OptionalChild",
    "RequiredChild",
    "OptionalDynamicChild",
    "RequiredDynamicChild",
    "OptionalXmlChild",
    "RequiredXmlChild",
)


def has_property_return(item: Item) -> bool:
    return item.kind == "method" and returns(item, *PROPERTY_MARKERS)


def has_child_return(item: Item) -> bool:
    return item.kind == "method" and returns(item, *CHILD_MARKERS)


def has_math_return(item: Item) -> bool:
    return item.kind == "method" and returns(item, "MathNode", "Vec<MathNode>", "SbmlUnits")


def rule_property(item: Item) -> bool:
    return is_accessor(item) and has_property_return(item)


def rule_child(item: Item) -> bool:
    return is_accessor(item) and has_child_return(item)


def rule_math_accessor(item: Item) -> bool:
    return is_accessor(item) and has_math_return(item)


def rule_constructor(item: Item) -> bool:
    """`new(..)`, `new_empty(..)`, `default(..)`: construct a wrapper for a document."""
    if item.kind != "method" or item.impl_trait:
        return False
    name = item.path.rpartition("::")[2]
    return name in {"new", "new_empty", "default", "new_empty_named"} or name.endswith("_new")


def rule_lookup(item: Item) -> bool:
    """`for_child_element` / `search_in_parents`: find a wrapper from an element."""
    if item.kind != "method" or item.impl_trait:
        return False
    name = item.path.rpartition("::")[2]
    return name in {"for_child_element", "search_in_parents", "find_by_sid", "find_by_meta_id",
                    "find_element_by_sid", "find_element_by_meta_id"}


def rule_sbase_accessor(item: Item) -> bool:
    return item.impl_trait == "SBase" and item.kind == "method"


def rule_xml_wrapper(item: Item) -> bool:
    """The `element` accessor of a wrapper type (not of the wrapper *machinery* types)."""
    return (
        item.impl_trait == "XmlWrapper"
        and item.kind == "method"
        and not item.path.startswith(("xml::XmlElement::", "xml::XmlList::"))
    )


def rule_sbml_object(item: Item) -> bool:
    return item.impl_trait == "SbmlObject"


def rule_standard_trait_member(item: Item) -> bool:
    return item.impl_trait in STANDARD_TRAITS


def rule_blanket(item: Item) -> bool:
    return item.impl_trait == "ExtensionCast"


