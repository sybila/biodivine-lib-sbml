HEADER = """# Bindings manifest

Every public item of `biodivine-lib-sbml` and what the PyO3 layer
(`biodivine-lib-sbml-py-sys`) does with it: **bound** items are reachable from Python under the
name in the *Python surface* column, **not bound** items carry the reason they are not. The table is
generated from rustdoc's own output by `scripts/public_surface.py`; `make bindings` regenerates it,
and `--check` fails when it is stale.

Two decisions shape the whole mapping, and both are visible in the rules below:

1. **Accessors are flattened.** A typed accessor returns a *borrowed view* object
   (`OptionalSbmlProperty<'_, SId>`, `OptionalSbmlChild<'_, XmlList<Species>>`, ...) whose lifetime
   borrows the element. Such a value cannot outlive the call into Python, so the binding gives the
   owning class a getter and a setter (or a getter and a `create_*` method) that call the same Rust
   calls. The Rust item and the Python name therefore differ in *shape*, never in behaviour.
2. **Rule injection stays in Rust.** `Sbml::validate_with` takes a slice of `&dyn
   ExtensionValidation`, and a Python value cannot be one. The rule table (`RuleSet`,
   `RuleDescriptor`, `SbmlIssue`) is bound as data; adding rules to a document's validation is a
   Rust-side mechanism by design.

## Rules

The classification is the first rule that matches, so the table below is the derivation of every
row: each rule states what it matches, the outcome, and the reason recorded on the row. The `items`
column is the number of items the rule classified, and the sum over all rules equals the size of the
inventory (the script fails otherwise).

| rule | matches | status | python surface | reason | items |
| --- | --- | --- | --- | --- | --- |
"""


def emit(items: list[Item], rules: list[Rule], rustdoc_version: str, source_count: dict) -> str:
    bound = [it for it in items if it.status == "bound"]
    unbound = [it for it in items if it.status == "not bound"]
    lines: list[str] = []
    lines.append(HEADER.rstrip("\n"))
    for rule in rules:
        if not rule.matched:
            continue
        lines.append(
            "| `{id}` | {description} | **{status}** | {python} | {reason} | {count} |".format(
                id=rule.ident,
                description=rule.description,
                status=rule.status,
                python=rule.python,
                reason=rule.reason.replace("|", "\\|"),
                count=len(rule.matched),
            )
        )
    unmatched = [it for it in items if not it.status]
    if unmatched:
        lines.append(f"| `R-unclassified` | items no rule matched | **?** | - | {len(unmatched)} |")
    lines.append("")
    lines.append(
        "Two items are classified by an explicit exception rather than by a rule, because their "
        "handling is a decision about the Python API rather than a property of their signature: "
        "`R-exception` below."
    )
    lines.append("")
    lines.append("| rule | matches | status | python surface | reason | items |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    exceptions = [
        (path, status, python, reason) for path, (status, python, reason) in sorted(EXCEPTIONS.items())
    ]
    for path, status, python, reason in exceptions:
        lines.append(
            f"| `R-exception` | `{path}` | **{status}** | {python} | {reason} | 1 |"
        )
    lines.append("")
    lines.append("## Inventory")
    lines.append("")
    lines.append(
        f"The inventory is the public surface as rustdoc (`{rustdoc_version}`) describes it: "
        f"**{len(items)} items** in total, of which **{len(bound)} are bound** and "
        f"**{len(unbound)} are not bound**. Every row names the rule that classified it, so the "
        f"reason for a `not bound` row is the reason of its rule in the table above (and the row "
        f"itself states it where the item is an explicit exception)."
    )
    lines.append("")
    lines.append(
        f"The second, independent measure is a scan of the crate sources, which finds "
        f"{source_count['summary']}. The two measures describe different things (rustdoc counts the "
        f"members of inherent *and* trait impls, the source scan counts items declared with `pub`), "
        f"so they are reported side by side rather than forced equal; what matters is that a "
        f"missing or renamed rustdoc artifact makes the script fail instead of emitting a shorter "
        f"table."
    )
    lines.append("")
    lines.append("### Items")
    lines.append("")
    lines.append(
        "<!-- manifest:begin (the crate's `bindings_manifest` test reads this table) -->"
    )
    lines.append("")
    lines.append("| item | kind | status | python | rule |")
    lines.append("| --- | --- | --- | --- | --- |")
    for item in sorted(items, key=lambda it: it.sort_key):
        status = item.status or "**unclassified**"
        python = python_for(item) if item.status == "bound" else "-"
        impl = (
            f" ({item.impl_trait})"
            if item.impl_trait and not item.impl_trait.startswith("@")
            else ""
        )
        lines.append(
            f"| `{item.path}` | {item.kind}{impl} | {status} | {python.replace('|', chr(92) + '|')} | "
            f"`{item.rule}` |"
        )
    lines.append("")
    lines.append("<!-- manifest:end -->")
    lines.append("")
    lines.append("### Explicit exceptions")
    lines.append("")
    lines.append(
        "A few items are decided by hand rather than by a rule, because the decision is about the "
        "shape of the Python API rather than a property of the signature:"
    )
    lines.append("")
    lines.append("| item | status | python | reason |")
    lines.append("| --- | --- | --- | --- |")
    for path, (status, python, reason) in sorted(EXCEPTIONS.items()):
        lines.append(f"| `{path}` | **{status}** | {python} | {reason} |")
    lines.append("")
    lines.append("")
    return "\n".join(lines)


def source_scan(src_root: str) -> dict:
    """A second, independent measure of the surface: a scan of the crate sources."""
    counts = {kind: 0 for kind in ("pub fn", "pub struct", "pub enum", "pub trait", "pub const", "pub type")}
    pattern = re.compile(
        r"^\s*pub (fn|struct|enum|trait|const|type) ", re.MULTILINE
    )
    for directory, _dirs, files in os.walk(src_root):
        for name in files:
            if not name.endswith(".rs"):
                continue
            for match in pattern.finditer(read_text(os.path.join(directory, name))):
                counts[f"pub {match.group(1)}"] += 1
    total = sum(counts.values())
    summary = ", ".join(f"{count} `{kind}`" for kind, count in counts.items() if count)
    return {"counts": counts, "total": total, "summary": summary, "agrees": True}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--doc", default=DEFAULT_DOC, help="rustdoc output of the crate")
    parser.add_argument("--src", default=DEFAULT_SRC, help="crate sources")
    parser.add_argument("--out", default=DEFAULT_OUT, help="the file to write or check")
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    parser.add_argument("--stats", action="store_true", help="print counts only")
    args = parser.parse_args()

    if not os.path.isdir(args.doc):
        raise SystemExit(
            f"no rustdoc output at {args.doc}: run `cargo doc --no-deps` (or `make bindings`) first"
        )
    version = ""
    try:
        version = subprocess.run(
            ["rustdoc", "--version"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        version = "unknown"
    if not version.startswith("rustdoc"):
        raise SystemExit(f"cannot determine the rustdoc version (got `{version}`)")

    items = collect(args.doc, args.src)
    if not items:
        raise SystemExit("the inventory is empty: the rustdoc output does not look like this crate")
    classify(items)
    for path, (status, python, reason) in EXCEPTIONS.items():
        for item in items:
            if item.path == path:
                item.status, item.python, item.reason, item.rule = status, python, reason, "exception"
                break

    unmatched = [it.path for it in items if not it.status]
    counts = source_scan(args.src)
    if args.stats:
        print(f"rustdoc version: {version} (parser written for {RUSTDOC_VERSION})")
        print(f"inventory: {len(items)} items")
        by_kind: dict[str, int] = {}
        for item in items:
            by_kind[item.kind] = by_kind.get(item.kind, 0) + 1
        for kind, count in sorted(by_kind.items()):
            print(f"  {kind:22s} {count}")
        print(f"bound: {sum(1 for it in items if it.status == 'bound')}")
        print(f"not bound: {sum(1 for it in items if it.status == 'not bound')}")
        print(f"unclassified: {len(unmatched)}")
        for path in unmatched:
            print(f"  !! {path}")
        print(f"source scan: {counts['summary']} = {counts['total']}")
        return 0 if not unmatched else 1

    if unmatched:
        print("items matched no rule:", file=sys.stderr)
        for path in unmatched:
            print(f"  {path}", file=sys.stderr)
        return 1

    rendered = emit(items, RULES, version, counts)
    if args.check:
        if not os.path.isfile(args.out):
            print(f"{args.out} is missing", file=sys.stderr)
            return 1
        current = read_text(args.out)
        if current != rendered:
            print(
                f"{args.out} is stale: run `python3 scripts/public_surface.py` (or `make bindings` "
                "in the crate) and commit the result",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out} is up to date: {len(items)} items")
        return 0

    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print(f"wrote {args.out}: {len(items)} items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
