#!/usr/bin/env python3
"""Derive the public surface of `biodivine-lib-sbml` and classify every item for the bindings.

The bindings layer (`biodivine-lib-sbml-py-sys`) is judged against `BINDINGS.md`: every public
item of the Rust crate appears there exactly once, marked *bound* (reachable from Python, with the
Python name) or *not bound* (with a reason). This script produces that file from rustdoc's own
output instead of from a hand-written list, so an item cannot be silently forgotten:

  * the item inventory comes from the generated documentation (`target/doc`), which rustdoc writes
    for the whole public surface: one entry per module item from the `sidebar-items.js` files, and
    one entry per member (method, associated constant, variant) from the item's own page;
  * the classification is a data table of *rules* (see `RULES`), the first matching rule wins, and
    every item records the rule that classified it -- so the file states its own derivation;
  * `--check` fails when the committed file is stale, when an item matched no rule, or when an item
    matched several rules.

Usage, from the repository root:

    python3 biodivine-lib-sbml-py-sys/scripts/public_surface.py            # rewrite the file
    python3 biodivine-lib-sbml-py-sys/scripts/public_surface.py --check     # verify it
    python3 biodivine-lib-sbml-py-sys/scripts/public_surface.py --stats     # counts only

The documentation is regenerated by `make bindings`, which runs `cargo doc --no-deps` first. The
parser is written against the HTML of the pinned stable toolchain (see `RUSTDOC_VERSION`); when a
renamed or missing artifact makes the inventory incomplete, the script fails instead of emitting a
shorter table, and `--stats` prints the second, independent measure (a scan of the crate sources)
next to the rustdoc count.
"""

