#!/usr/bin/env python3
"""Shared helpers for the corpus measurement tools of this crate.

The three tools that use this module are the ones that measure the syntactic test suite
from outside the Rust code:

  * `scripts/corpus_census.py` turns the report files of the `test-suite-syntactic` example
    into the pinned pass-rate metric (mismatch documents and mismatch events, by rule and by
    rule family);
  * `scripts/corpus_worklist.py` ranks the rules of the corpus by how much of the metric each
    of them accounts for;
  * `scripts/snapshot_diff.py` attributes a change of the recorded whole-corpus snapshots to a
    rule and a kind of change.

Everything here is plain text handling of two file formats:

  * a *report file* is one line per mismatch, written by the example:
    `Test <rule-directory>/<file>: Missed issue <id> (severity "<Severity>").` or the same with
    `Found unexpected issue`;
  * a *sorted snapshot* is the `sort | uniq -c` form of a report file, which is what
    `scripts/full-corpus-baseline/` holds: `<count> <line>`.

Two counting rules are used throughout and are stated once here:

  * an **event** is one reported mismatch line, counted with multiplicity. Ten documents with
    the same expected issue are ten events.
  * a **document** is one `Test <rule-directory>/<file>` name; the metric counts each document
    once, however many events it contributes.

The distinction matters: the lexical size of a report file (`wc -l` of its sorted form, where
identical lines collapse) is a third number that appears in no table of this repository.

## The two rule taxonomies, and which one is a scope claim

Two ways of labeling a rule id exist here and they answer different questions:

  * **provenance** ([`provenance_of`], [`scope_of`], [`scope_label`]) answers "which
    specification defines this id?". It is read from the crate's own spec-derived id list
    (`spec-coverage/rules.csv`, generated by `scripts/spec_coverage.py` from the LaTeX sources of
    the specification checkout), so an id is *in scope* because a specification document defines
    it - never because it starts with a particular digit. An id no specification defines is
    reported as such ([`NO_OWNING_SPECIFICATION`]), never as "libSBML-only by number". This is the
    taxonomy every scope decision and every ranking is built on.
  * **the numeric family** ([`family_of`]) is the *secondary*, shape-based heuristic taken from
    `syntactic/README.md`: directories whose name is a five-digit number from 5xxxx to 79999 are
    rules of an SBML core specification (Level 2 Version 2 and later, and Level 3), directories
    named `8xxxx`/`9xxxx` are libSBML's own rules, and a name of the form `<package>-<number>` is a
    rule of that package's specification. It is kept because every published report of this
    repository labels its tables this way, so a reader can follow the movement between the two; it
    is **not** a scope claim, and the two disagree on exactly the ids the provenance table of a
    report has to name (`comp-9xxxx`, `fbc-204xx`, the `0xxxx` family).

When `spec-coverage/rules.csv` is absent (a checkout without a generated matrix), the provenance
functions degrade to the numeric heuristic and the tools that print a provenance table say so
rather than inventing a partition.

The expected-rule index ([`syntactic/README.md`]-style rule directories) and the report files are
read as described below.
"""

from __future__ import annotations

import csv
import collections
import os
import re

#: One mismatch line of a report file.
MISMATCH = re.compile(
    r'^Test (?P<doc>[^:]+): (?:(?P<kind>Missed|Found unexpected) )?'
    r'issue (?P<rule>[0-9a-zA-Z_-]+) \(severity "(?P<severity>\w+)"\)\.$'
)
#: One line of a sorted snapshot: a count, a space, then the report line. Which report the
#: line belongs to is decided by the caller (`MISMATCH` validates the three mismatch reports;
#: the issue dump and the round-trip report use their own, pipe-separated form).
SORTED = re.compile(r"^\s*(?P<count>\d+) (?P<line>.*)$")
#: The rule directories of a package specification, e.g. `fbc-21207` or `qual-20406`.
PACKAGE_ID = re.compile(r"^(?P<package>[a-z]+)-(?P<number>\d+)$")


#: The line the harness prints before it reads and validates one document.
TESTING_LINE = re.compile(r'^ > Testing "(?P<path>[^"]+)"')

#: The value [`scope_of`] returns for an id no specification defines.
NO_OWNING_SPECIFICATION = "no-owning-specification"

#: The crate root, derived from this file (`<root>/scripts/corpus_lib.py`).
CRATE_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

#: The generated coverage matrix: the crate's own spec-derived id list.
COVERAGE_MATRIX = os.path.join(CRATE_ROOT, "spec-coverage", "rules.csv")

_spec_owners: dict[str, tuple[str, ...]] | None = None


def spec_rule_owners() -> dict[str, tuple[str, ...]]:
    """The specification-defined rule ids, as `rule id -> the packages that define it`.

    Read from `spec-coverage/rules.csv`, whose rows are one (level, version, package, rule id)
    entry per rule of a specification document. An id defined by more than one package (the `dyn`
    package re-states some `comp` rules) keeps every owner, sorted, because "which specification
    defines this id" has no single answer for it.

    Returns an empty mapping when the matrix is absent, which the callers report as "the provenance
    table is unavailable" instead of silently falling back to a shape-based guess.
    """
    global _spec_owners
    if _spec_owners is not None:
        return _spec_owners
    owners: dict[str, set[str]] = {}
    if os.path.exists(COVERAGE_MATRIX):
        with open(COVERAGE_MATRIX, encoding="utf-8") as source:
            for row in csv.DictReader(source):
                rule = row.get("rule_id", "")
                if rule in ("", "-"):
                    continue
                owners.setdefault(rule, set()).add(row["package"])
    _spec_owners = {rule: tuple(sorted(packages)) for rule, packages in owners.items()}
    return _spec_owners


def provenance_available() -> bool:
    """Whether the spec-derived id list exists, i.e. whether a provenance partition is possible."""
    return bool(spec_rule_owners())


def has_spec_provenance(rule: str) -> bool:
    """Whether some specification document defines `rule` (the scope test of a rule id)."""
    return rule in spec_rule_owners()


def provenance_of(rule: str) -> tuple[str, tuple[str, ...]]:
    """Classify `rule` and name its owners.

    Returns one of three classes:

      * `("spec", packages)` - a specification document defines the id, in the named package(s);
      * `("lint", ())` - the id is a word, not a rule id of any specification: the library's own
        diagnostics (`not-validated`, `unused-namespace`, `SANITY_CHECK`, `unmodelled-level`);
      * `(NO_OWNING_SPECIFICATION, ())` - the id has the *shape* of a rule id but no specification
        document in this checkout defines it. That is the disagreement with the numeric heuristic,
        and it is a decision, not an oversight: implementing such an id would implement somebody
        else's validator rather than a rule of the standard.
    """
    owners = spec_rule_owners().get(rule)
    if owners:
        return "spec", owners
    if re.fullmatch(r"[0-9]{5}", rule) is None and PACKAGE_ID.match(rule) is None:
        # Neither a five-digit rule number nor `<package>-<number>`: the id is a word, which is the
        # shape of the library's own diagnostics and of nothing else in this corpus.
        return "lint", ()
    return NO_OWNING_SPECIFICATION, ()


def scope_of(rule: str) -> str:
    """The specification a rule id belongs to, as a scope key.

    Returns `core` for a rule of an SBML core specification, `package:<name>` for one of an
    extension package, `library-lint` for one of the library's own diagnostics, and
    [`NO_OWNING_SPECIFICATION`] for a rule-id-shaped id that no specification defines.

    This is the *provenance* answer ([`provenance_of`]), not the numeric heuristic: the `0xxxx`,
    `8xxxx` and `9xxxx` families are not automatically "core" or "libSBML", they are whatever the
    spec-derived id list says, and an id the list does not hold is no specification's rule.
    """
    kind, owners = provenance_of(rule)
    if kind == "spec":
        if owners == ("core",):
            return "core"
        return "package:" + "+".join(owners)
    if kind == "lint":
        return "library-lint"
    return NO_OWNING_SPECIFICATION


def family_of(rule: str) -> str:
    """The *numeric* family a rule id belongs to, for the shape-based partition of the metric.

    This is the heuristic of `syntactic/README.md`, not a scope claim ([`scope_of`] is the scope
    claim). It is what the earlier reports of this repository label their tables with, so a report
    can show how the two partitions move events between buckets.
    """
    match = PACKAGE_ID.match(rule)
    if match is not None:
        return f"package:{match.group('package')}"
    if re.fullmatch(r"[0-9]{5}", rule) is not None:
        first = rule[0]
        if first in "89":
            return f"libsbml-{first}xxxx"
        if first in "12":
            return f"core-{first}xxxx"
        return f"core-{first}xxxx"
    return "library-lint"


def scope_label(rule: str) -> str:
    """Which part of the work a rule id belongs to, for the scope column of the tables.

    Three of the four answers are about the *declared standard*: a rule of an SBML core
    specification is the work of the unit that owns the core, a rule of an extension package
    belongs to the unit that owns that package, and an id no specification defines belongs to
    nobody, because implementing one would invent a rule of the standard rather than implement it.
    """
    kind, owners = provenance_of(rule)
    if kind == "spec":
        if owners == ("core",):
            return "core (this unit)"
        return "package " + "+".join(owners) + " (package unit)"
    if kind == "lint":
        return "library lint (this unit)"
    return "no owning specification (out of scope)"



def read_report(path: str) -> list[tuple[str, str, str]]:
    """Read one report file into `(document, kind, rule_id)` triples, one per line.

    `kind` is `Missed` or `Found unexpected`; a missing kind is treated as `Missed` (the
    report's own vocabulary).
    """
    events = []
    if not os.path.exists(path):
        return events
    with open(path, encoding="utf-8") as source:
        for raw in source:
            raw = raw.rstrip("\n")
            if not raw.strip():
                continue
            match = MISMATCH.match(raw)
            if match is None:
                raise SystemExit(f"unparsable report line in {path}: {raw}")
            events.append(
                (match.group("doc"), match.group("kind") or "Missed", match.group("rule"))
            )
    return events


def read_snapshot(path: str) -> collections.Counter:
    """Read a sorted snapshot into a `Counter` of report line -> occurrence count."""
    lines = collections.Counter()
    if not os.path.exists(path):
        return lines
    with open(path, encoding="utf-8") as source:
        for raw in source:
            raw = raw.rstrip("\n")
            if not raw.strip():
                continue
            match = SORTED.match(raw)
            if match is None:
                raise SystemExit(f"unparsable snapshot line in {path}: {raw}")
            lines[match.group("line")] += int(match.group("count"))
    return lines


def mismatch_index(events) -> dict[str, set[tuple[str, str]]]:
    """Group `(document, kind, rule)` triples into `document -> {(kind, rule)}`."""
    index: dict[str, set[tuple[str, str]]] = collections.defaultdict(set)
    for document, kind, rule in events:
        index[document].add((kind, rule))
    return dict(index)


def parse_expectation(path: str) -> collections.Counter | None:
    """Read one `.txt` expectation file into a `Counter` of rule id -> expected events.

    Returns `None` when the file does not exist, which is how a document without an
    expectation file is represented.
    """
    if not os.path.exists(path):
        return None
    expected: collections.Counter = collections.Counter()
    last_rule = None
    with open(path, encoding="utf-8") as source:
        for line in source:
            parts = line.split(":")
            if len(parts) != 2:
                continue
            if parts[0].strip() == "Validation id":
                last_rule = parts[1].strip()
            elif parts[0].strip() == "Severity":
                if last_rule is None:
                    raise SystemExit(f"severity without a rule id in {path}")
                expected[last_rule] += 1
                last_rule = None
    return expected


def corpus_documents(corpus: str, versions=("l3v2", "l3v1")):
    """Yield `(document, rule_directory, expectation_path)` for every document the harness reads.

    The harness reads a document whose file name contains `l3v2` as it is, and one that
    contains `l3v1` after replacing the Level 3 Version 1 core namespace with the Version 2
    one; every other file name is skipped. This function mirrors that selection.
    """
    for rule_directory in sorted(os.listdir(corpus)):
        directory = os.path.join(corpus, rule_directory)
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if not name.endswith(".xml"):
                continue
            if not any(version in name for version in versions):
                continue
            document = f"{rule_directory}/{name}"
            expectation = os.path.join(directory, name.replace(".xml", ".txt"))
            yield document, rule_directory, expectation
